import { chromium } from 'playwright';
import fs from 'node:fs';
const BASE='http://localhost:4173';
const browser=await chromium.launch({headless:true});
const ctx=await browser.newContext({viewport:{width:1440,height:900}});
const entries=Object.entries(JSON.parse(fs.readFileSync('scripts/qa/fixtures/seeded.json','utf8')));
await ctx.addInitScript(([pairs])=>{for(const [k,v] of pairs)localStorage.setItem(k,typeof v==='string'?v:JSON.stringify(v));},[entries]);
const page=await ctx.newPage();
page.on('console',m=>console.log('CONSOLE',m.type(),m.text()));
page.on('pageerror',e=>console.log('PAGEERROR',String(e)));
await page.goto(BASE+'/settings',{waitUntil:'domcontentloaded'});
await page.waitForTimeout(4000);
console.log('URL',page.url());
await page.screenshot({path:'qa-shots/swarm/04-settings-test.png'});
await browser.close();
